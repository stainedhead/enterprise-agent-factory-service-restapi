func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.NewReplacer("`", "").Replace(s)
}

func genSettings(ex *Extract) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package domain\n\nimport (\n\t\"bytes\"\n\t\"encoding/json\"\n\t\"fmt\"\n\t\"regexp\"\n)\n\n")
	b.WriteString(settingSpecType)
	b.WriteString("// Service setting keys of root PRD §6.13.\nconst (\n")
	for _, s := range ex.Settings {
		fmt.Fprintf(&b, "\t// Setting%s is %q (default %s; %s).\n\tSetting%s = %q\n", goName(s.Key), s.Key, mustJSON(s.Default), oneLine(s.Allowed), goName(s.Key), s.Key)
	}
	b.WriteString(")\n\n")
	b.WriteString("// SettingSpecs lists every service setting with its type, default and range, in PRD order.\nvar SettingSpecs = []SettingSpec{\n")
	for _, s := range ex.Settings {
		fmt.Fprintf(&b, "\t{Key: Setting%s, Type: %q, Default: %q", goName(s.Key), s.Type, mustJSON(s.Default))
		if s.Nullable {
			b.WriteString(", Nullable: true")
		}
		if s.Min != nil {
			fmt.Fprintf(&b, ", Min: ptr(int64(%d)), Max: ptr(int64(%d))", *s.Min, *s.Max)
		}
		if s.Pattern != "" {
			fmt.Fprintf(&b, ", Pattern: %q", s.Pattern)
		}
		if s.Items != "" {
			fmt.Fprintf(&b, ", Items: %q", s.Items)
		}
		fmt.Fprintf(&b, ", Allowed: %q},\n", oneLine(s.Allowed))
	}
	b.WriteString("}\n\nfunc ptr[T any](v T) *T { return &v }\n")
	return b.Bytes()
}

const settingSpecType = `// SettingSpec describes one service setting: its JSON type, default (JSON text), range and pattern.
type SettingSpec struct {
	Key      string
	Type     string // string, boolean, integer or array (of strings)
	Default  string
	Nullable bool
	Min, Max *int64
	Pattern  string
	Items    string
	Allowed  string
}

// SettingSpecFor returns the spec of key.
func SettingSpecFor(key string) (SettingSpec, bool) {
	for _, s := range SettingSpecs {
		if s.Key == key {
			return s, true
		}
	}
	return SettingSpec{}, false
}

// Validate checks a JSON value against the spec. The database checks the same rules again.
func (s SettingSpec) Validate(raw json.RawMessage) error {
	bad := func(reason string) error { return Validation(FieldError{Field: "value", Reason: reason}) }
	raw = bytes.TrimSpace(raw)
	if string(raw) == "null" {
		if s.Nullable {
			return nil
		}
		return bad(s.Key + " may not be null")
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var v any
	if err := dec.Decode(&v); err != nil || dec.More() {
		return bad("must be JSON")
	}
	switch s.Type {
	case "boolean":
		if _, ok := v.(bool); !ok {
			return bad(s.Key + " must be a boolean")
		}
	case "integer":
		n, ok := v.(json.Number)
		i, err := n.Int64()
		if !ok || err != nil {
			return bad(s.Key + " must be an integer")
		}
		if (s.Min != nil && i < *s.Min) || (s.Max != nil && i > *s.Max) {
			return bad(fmt.Sprintf("%s must be %d to %d", s.Key, *s.Min, *s.Max))
		}
	case "string":
		str, ok := v.(string)
		if !ok {
			return bad(s.Key + " must be a string")
		}
		if s.Pattern != "" && !regexp.MustCompile(s.Pattern).MatchString(str) {
			return bad(s.Key + " must match " + s.Pattern)
		}
	case "array":
		arr, ok := v.([]any)
		if !ok {
			return bad(s.Key + " must be an array")
		}
		for _, e := range arr {
			str, ok := e.(string)
			if !ok || (s.Pattern != "" && !regexp.MustCompile(s.Pattern).MatchString(str)) {
				return bad(s.Key + " items must match " + s.Pattern)
			}
		}
	}
	return nil
}

`

func mustJSON(v any) string {
	b, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	return string(b)
}
