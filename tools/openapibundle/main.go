// Command openapibundle merges the hand-written OpenAPI fragments under api/src into one sorted,
// stable document (api/openapi.yaml). With -check it fails when the committed bundle differs.
//
// Layout of the source directory:
//
//	openapi.base.yaml     openapi, info, servers, security, tags, x- extensions
//	components/*.yaml     each a map of component kinds (schemas, parameters, responses, headers, ...)
//	paths/*.yaml          each a map of path → path item
//	schemas/*.yaml        each a map of schema name → schema (merged into components.schemas)
//
// A key defined twice (a path, a method, a component) is an error, so fragments never override
// each other.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"

	"gopkg.in/yaml.v3"
)

const banner = "# Code generated by tools/openapibundle from api/src; DO NOT EDIT. Run make openapi.\n"

func main() {
	src := flag.String("src", "api/src", "fragment directory")
	out := flag.String("out", "api/openapi.yaml", "bundle path")
	check := flag.Bool("check", false, "fail when the bundle differs instead of writing")
	flag.Parse()
	b, err := Bundle(*src)
	if err != nil {
		fmt.Fprintln(os.Stderr, "openapibundle:", err)
		os.Exit(1)
	}
	if *check {
		got, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(got, b) {
			fmt.Fprintf(os.Stderr, "openapibundle: %s is not the bundle of %s; run make openapi\n", *out, *src)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, b, 0o600); err != nil {
		fmt.Fprintln(os.Stderr, "openapibundle:", err)
		os.Exit(1)
	}
}

// Bundle reads the fragments under src and returns the bundled document.
func Bundle(src string) ([]byte, error) {
	base, err := readMap(filepath.Join(src, "openapi.base.yaml"))
	if err != nil {
		return nil, err
	}
	paths := map[string]any{}
	if existing, ok := base["paths"].(map[string]any); ok {
		paths = existing
	}
	components := map[string]any{}
	if existing, ok := base["components"].(map[string]any); ok {
		components = existing
	}
	files, err := glob(src, "components")
	if err != nil {
		return nil, err
	}
	for _, f := range files {
		m, err := readMap(f)
		if err != nil {
			return nil, err
		}
		if err := merge(components, m, "components", f); err != nil {
			return nil, err
		}
	}
	files, err = glob(src, "schemas")
	if err != nil {
		return nil, err
	}
	for _, f := range files {
		m, err := readMap(f)
		if err != nil {
			return nil, err
		}
		if err := merge(components, map[string]any{"schemas": m}, "components", f); err != nil {
			return nil, err
		}
	}
	files, err = glob(src, "paths")
	if err != nil {
		return nil, err
	}
	for _, f := range files {
		m, err := readMap(f)
		if err != nil {
			return nil, err
		}
		if err := merge(paths, m, "paths", f); err != nil {
			return nil, err
		}
	}
	base["paths"] = paths
	base["components"] = components
	var buf bytes.Buffer
	buf.WriteString(banner)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(base); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func glob(src, dir string) ([]string, error) {
	files, err := filepath.Glob(filepath.Join(src, dir, "*.yaml"))
	if err != nil {
		return nil, err
	}
	slices.Sort(files)
	return files, nil
}

// readMap decodes a YAML file into a map with string keys at every level.
func readMap(path string) (map[string]any, error) {
	raw, err := os.ReadFile(path) //nolint:gosec // developer tool reading the repository's own files
	if err != nil {
		return nil, err
	}
	var v any
	if err := yaml.Unmarshal(raw, &v); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if v == nil {
		return map[string]any{}, nil
	}
	m, ok := normalize(v).(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s: top level is not a mapping", path)
	}
	return m, nil
}

// normalize turns every mapping key into a string (response codes such as 200).
func normalize(v any) any {
	switch t := v.(type) {
	case map[string]any:
		for k, e := range t {
			t[k] = normalize(e)
		}
		return t
	case map[any]any:
		m := make(map[string]any, len(t))
		for k, e := range t {
			m[fmt.Sprint(k)] = normalize(e)
		}
		return m
	case []any:
		for i, e := range t {
			t[i] = normalize(e)
		}
		return t
	}
	return v
}

var errDuplicate = errors.New("defined twice")

// merge adds src into dst two levels deep (kind → name, or path → method), refusing duplicates.
func merge(dst, src map[string]any, where, file string) error {
	for k, v := range src {
		existing, ok := dst[k]
		if !ok {
			dst[k] = v
			continue
		}
		em, ok1 := existing.(map[string]any)
		vm, ok2 := v.(map[string]any)
		if !ok1 || !ok2 {
			return fmt.Errorf("%s: %s.%s %w", file, where, k, errDuplicate)
		}
		for k2, v2 := range vm {
			if _, dup := em[k2]; dup {
				return fmt.Errorf("%s: %s.%s.%s %w", file, where, k, k2, errDuplicate)
			}
			em[k2] = v2
		}
	}
	return nil
}
